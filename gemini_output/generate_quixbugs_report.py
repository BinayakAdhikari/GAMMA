import os

def generate_quixbugs_report(
    meta_path=r"E:\Marburg Uni\Third Semester\GAMMA Seminar\GAMMA\patchGeneration\quixbugs_meta.txt",
    input_lines_path=r"E:\Marburg Uni\Third Semester\GAMMA Seminar\GAMMA\patchGeneration\inputLines_quixbugs.txt",
    results_dir=r"E:\Marburg Uni\Third Semester\GAMMA\results\unixcoder_results"
): 
    report_content = []

    report_content.append("# UniXcoder Patching Report for QuixBugs Dataset\n")
    report_content.append("This report summarizes the application of the UniXcoder model for patching simulated bugs in the QuixBugs dataset.\n")
    report_content.append("It details the buggy programs, the patching methodology, and presents examples of the generated patches.\n\n")

    # --- Section 1: QuixBugs Dataset Overview ---
    report_content.append("## 1. QuixBugs Dataset Overview\n")
    buggy_programs = []
    try:
        with open(meta_path, "r") as f_meta:
            for line in f_meta:
                parts = line.strip().split('\t')
                if len(parts) >= 4:
                    program_name = parts[0]
                    buggy_line_num = parts[2]
                    description = parts[3]
                    buggy_programs.append((program_name, buggy_line_num, description))
        report_content.append(f"Total number of buggy QuixBugs programs analyzed: {len(buggy_programs)}\n\n")
        report_content.append("| Program Name | Buggy Line Number | Bug Description |\n")
        report_content.append("|--------------|-------------------|-----------------|\n")
        for program_name, line_num, desc in buggy_programs:
            report_content.append(f"| {program_name} | {line_num} | {desc} |\n")
        report_content.append("\n")
    except FileNotFoundError:
        report_content.append(f"Error: QuixBugs metadata file not found at {meta_path}\n\n")
        buggy_programs = [] # Ensure it's empty if file not found

    # --- Section 2: Patching Methodology ---
    report_content.append("## 2. Patching Methodology\n")
    report_content.append("The patching process utilizes the UniXcoder model. For each buggy code snippet, the line identified as buggy is replaced with a `<mask0>` token. The UniXcoder model then attempts to 'fill' this mask, generating potential fixes for the masked line. These generated lines are considered the patches.\n\n")
    report_content.append("The `unixcoder_repair.py` script orchestrates this process, reading buggy code and metadata, inserting the mask, and using the UniXcoder model to generate and save the patches.\n\n")

    # --- Section 3: Generated Patches (Examples) ---
    report_content.append("## 3. Generated Patches\n")
    report_content.append("This section presents the original buggy code snippets and the corresponding patches generated by UniXcoder. Please note that the 'fixed' or 'plausible' status of these patches requires further validation through testing.\n\n")

    buggy_snippets = []
    try:
        with open(input_lines_path, "r") as f_input:
            buggy_snippets = f_input.readlines()
    except FileNotFoundError:
        report_content.append(f"Error: Input buggy lines file not found at {input_lines_path}\n\n")

    if buggy_programs and buggy_snippets:
        for i, (program_name, buggy_line_str, desc) in enumerate(buggy_programs):
            if i < len(buggy_snippets):
                original_snippet = buggy_snippets[i].strip()
                buggy_line_num = int(buggy_line_str)

                report_content.append(f"### {program_name} (Buggy Line: {buggy_line_num})\n")
                report_content.append("#### Original Buggy Code:\n")
                report_content.append("```python\n")
                # Highlight the buggy line if possible
                lines = original_snippet.split('\n')
                for idx, line in enumerate(lines):
                    if idx == buggy_line_num - 1:
                        report_content.append(f">> {line}\n")
                    else:
                        report_content.append(f"   {line}\n")
                report_content.append("```\n")

                # Read generated patch
                patch_file_name = f"{i+1:03d}_line{buggy_line_num}.txt"
                patch_file_path = os.path.join(results_dir, patch_file_name)
                
                report_content.append("#### Generated Patch(es):\n")
                try:
                    with open(patch_file_path, "r") as f_patch:
                        patches = f_patch.readlines()
                        if patches:
                            report_content.append("```python\n")
                            for patch_line in patches:
                                report_content.append(f"{patch_line.strip()}\n")
                            report_content.append("```\n")
                        else:
                            report_content.append("No patches generated for this snippet.\n")
                except FileNotFoundError:
                    report_content.append(f"No patch file found at {patch_file_path}\n")
                except Exception as e:
                    report_content.append(f"Error reading patch file: {e}\n")
                report_content.append("\n")
            else:
                report_content.append(f"Warning: No buggy snippet found for {program_name} at index {i}.\n\n")
    else:
        report_content.append("Could not generate patch examples due to missing input files.\n")

    # --- Conclusion ---
    report_content.append("## Conclusion\n")
    report_content.append("This report provides an overview of the UniXcoder's performance in generating patches for the QuixBugs dataset. The effectiveness of these generated patches in truly fixing the bugs would require a comprehensive testing framework.\n")

    # Write the report to a file
    output_report_path = r"E:\Marburg Uni\Third Semester\GAMMA Seminar\GAMMA\gemini_output\quixbugs_patching_report.md"
    with open(output_report_path, "w") as f_out:
        f_out.writelines(report_content)
    
    print(f"Report generated successfully at: {output_report_path}")

if __name__ == "__main__":
    generate_quixbugs_report()
